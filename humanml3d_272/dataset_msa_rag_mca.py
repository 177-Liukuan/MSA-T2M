"""RAG + Multi-Text-CA dataloader for MotionStreamer Stage-2 MCA training.

Extends dataset_msa_rag with word-level T5 token embeddings so that the
LLaMARAGMultiTextCAWrapper can inject them via cross-attention.

Extra files expected (generated by get_text_token_latent_t5.py)
---------------------------------------------------------------
  text_token_latent_dir/{id}.npz
      embs    : (num_captions, max_token_len, 768)  float32 – padded
      lengths : (num_captions,)                     int32

Batch output format (extends dataset_msa_rag)
---------------------------------------------
  text_emb         : (B, 768)
  top_hcls         : (B, K, 768)
  top_scores       : (B, K)
  motion_latents   : (B, T, latent_dim)
  text_token_embs  : (B, S_max, 768)   – padded to max in batch
  text_token_lens  : (B,)              – valid token counts

If text_token_latent_dir is None, the last two items are zero-tensors
so that LLaMARAGMultiTextCAWrapper can receive them as text_tokens=None.
"""

import os
import random
import codecs as cs
from os.path import join as pjoin

import numpy as np
import torch
from torch.utils import data
from tqdm import tqdm

from humanml3d_272.dataset_msa_rag import (
    Text2MotionMSARAGDataset,
    cycle,
)


class Text2MotionMSARAGMCADataset(data.Dataset):
    """RAG dataset augmented with word-level T5 token embeddings.

    Parameters
    ----------
    text_token_latent_dir : str | None
        Directory of .npz files with word-level T5 token embeddings.
        Pass None to disable token loading (text_tokens will be None).
    All other parameters are forwarded to Text2MotionMSARAGDataset.
    """

    def __init__(
        self,
        dataset_name='t2m_272',
        motion_latent_dir='./humanml3d_272/t2m_latents_msa_vae/exp',
        text_latent_dir='./humanml3d_272/text_latents_t5',
        hcls_dir='./humanml3d_272/h_cls_latents_msa_vae/exp',
        text_token_latent_dir=None,   # NEW: per-word T5 token embeddings
        topk=3,
        exclude_self=True,
        text_embed_dim=None,
    ):
        # Re-use all base functionality (library construction, etc.)
        self._base = Text2MotionMSARAGDataset(
            dataset_name=dataset_name,
            motion_latent_dir=motion_latent_dir,
            text_latent_dir=text_latent_dir,
            hcls_dir=hcls_dir,
            topk=topk,
            exclude_self=exclude_self,
            text_embed_dim=text_embed_dim,
        )
        self.text_token_latent_dir = text_token_latent_dir
        self.text_embed_dim = self._base.text_embed_dim

        if text_token_latent_dir is not None:
            if not os.path.isdir(text_token_latent_dir):
                raise FileNotFoundError(
                    f'text_token_latent_dir not found: {text_token_latent_dir}'
                )
            # Verify at least one expected file is present
            first_id = self._base.data[0]['id']
            check_path = pjoin(text_token_latent_dir, first_id + '.npz')
            if not os.path.exists(check_path):
                raise FileNotFoundError(
                    f'Token-level embedding file not found: {check_path}\n'
                    '  Run get_text_token_latent_t5.py first.'
                )
            print(f'[MCA Dataset] token latents: {text_token_latent_dir}')
        else:
            print('[MCA Dataset] text_token_latent_dir=None → CA disabled (text_tokens=None)')

    def __len__(self):
        return len(self._base)

    def __getitem__(self, idx):
        entry = self._base.data[idx]

        # ---------- 1. Motion latents ----------
        motion_latents = np.load(entry['motion_path']).astype(np.float32)

        # ---------- 2. Sentence-level text embedding (same as base) ----------
        text_all = np.load(entry['text_path']).astype(np.float32)
        if text_all.ndim == 2 and text_all.shape[0] > 1:
            caption_idx = random.randint(0, text_all.shape[0] - 1)
            text_emb = text_all[caption_idx]
        elif text_all.ndim == 2:
            caption_idx = 0
            text_emb = text_all[0]
        else:
            caption_idx = 0
            text_emb = text_all.reshape(-1)

        if text_emb.shape[0] != self.text_embed_dim:
            raise ValueError(
                f"text_emb dim mismatch for {entry['id']}: "
                f"got {text_emb.shape[0]}, expected {self.text_embed_dim}"
            )

        # ---------- 3. RAG retrieval (same as base) ----------
        text_query = torch.from_numpy(text_emb).float().unsqueeze(0)
        text_query = self._base._l2_normalize(text_query)
        sim = torch.matmul(text_query, self._base.library_hcls_norm.t()).squeeze(0)

        if self._base.exclude_self and entry['id'] in self._base.id_to_library_index:
            sim[self._base.id_to_library_index[entry['id']]] = -1e6

        k = min(self._base.topk, sim.shape[0])
        top_scores, top_indices = torch.topk(sim, k=k, dim=0)
        top_hcls = self._base.library_hcls[top_indices]

        if k < self._base.topk:
            pad_h = torch.zeros(self._base.topk - k, self.text_embed_dim, dtype=top_hcls.dtype)
            pad_s = torch.full((self._base.topk - k,), -1e6, dtype=top_scores.dtype)
            top_hcls = torch.cat([top_hcls, pad_h], dim=0)
            top_scores = torch.cat([top_scores, pad_s], dim=0)

        # ---------- 4. Word-level token embeddings ----------
        if self.text_token_latent_dir is not None:
            token_path = pjoin(self.text_token_latent_dir, entry['id'] + '.npz')
            npz = np.load(token_path)
            token_embs_all = npz['embs'].astype(np.float32)  # (num_caps, max_len, 768)
            token_lens_all = npz['lengths'].astype(np.int32)  # (num_caps,)

            # Use same caption_idx as sentence embedding selection, clamped for safety
            cap_idx_clamped = min(caption_idx, token_embs_all.shape[0] - 1)
            token_emb = token_embs_all[cap_idx_clamped]          # (max_len, 768)
            token_len = int(token_lens_all[cap_idx_clamped])
            # Trim to valid length to save memory
            token_emb = token_emb[:token_len]                    # (token_len, 768)
        else:
            token_emb = None
            token_len = 0

        return (
            text_emb.astype(np.float32),
            top_hcls.numpy().astype(np.float32),
            top_scores.numpy().astype(np.float32),
            motion_latents.astype(np.float32),
            token_emb,     # (token_len, 768) or None
            token_len,     # int
        )


def collate_fn_mca(batch):
    text_embs, top_hcls_list, top_scores_list, motion_list, token_emb_list, token_len_list = zip(*batch)

    text_emb_batch = torch.from_numpy(np.stack(text_embs)).float()
    top_hcls_batch = torch.from_numpy(np.stack(top_hcls_list)).float()
    top_scores_batch = torch.from_numpy(np.stack(top_scores_list)).float()

    max_motion = max(seq.shape[0] for seq in motion_list)
    latent_dim = motion_list[0].shape[1]
    motion_batch = torch.zeros(len(motion_list), max_motion, latent_dim, dtype=torch.float32)
    for i, seq in enumerate(motion_list):
        motion_batch[i, : seq.shape[0]] = torch.from_numpy(seq).float()

    # Word-level token embeddings (variable length per sample)
    token_lens = torch.tensor(token_len_list, dtype=torch.long)

    if any(e is not None for e in token_emb_list):
        text_dim = next(e for e in token_emb_list if e is not None).shape[-1]
        max_tok = max(max(l for l in token_len_list), 1)
        token_emb_batch = torch.zeros(
            len(token_emb_list), max_tok, text_dim, dtype=torch.float32
        )
        for i, emb in enumerate(token_emb_list):
            if emb is not None and emb.shape[0] > 0:
                L = emb.shape[0]
                token_emb_batch[i, :L] = torch.from_numpy(emb).float()
    else:
        token_emb_batch = None   # collated as None → model skips CA

    return text_emb_batch, top_hcls_batch, top_scores_batch, motion_batch, token_emb_batch, token_lens


def DATALoader(
    dataset_name,
    is_test,
    batch_size,
    motion_latent_dir,
    text_latent_dir,
    hcls_dir,
    text_token_latent_dir=None,
    topk=3,
    exclude_self=True,
    num_workers=0,
    text_embed_dim=None,
):
    _ = is_test
    dataset = Text2MotionMSARAGMCADataset(
        dataset_name=dataset_name,
        motion_latent_dir=motion_latent_dir,
        text_latent_dir=text_latent_dir,
        hcls_dir=hcls_dir,
        text_token_latent_dir=text_token_latent_dir,
        topk=topk,
        exclude_self=exclude_self,
        text_embed_dim=text_embed_dim,
    )
    loader = torch.utils.data.DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        collate_fn=collate_fn_mca,
        drop_last=True,
        persistent_workers=(num_workers > 0),  # keep workers alive between batches
        pin_memory=True,                        # faster CPU→GPU transfer
    )
    return loader
